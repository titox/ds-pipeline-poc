// Component status. Run with: npm run status
//   npm run status              writes docs/components.md
//   npm run status -- --check   writes nothing; exit code 1 if docs/components.md is out of date
// One row per contract in docs/components/. Every cell is read from a file of the repository,
// so the status is calculated, never typed. Nobody edits docs/components.md by hand.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const at = (...p) => path.join(root, ...p);
const exists = (...p) => fs.existsSync(at(...p));
const read = (...p) => fs.readFileSync(at(...p), "utf8");

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}
const nodeIdOf = (url) => (url?.match(/node-id=([\d]+[-:][\d]+)/)?.[1] ?? "").replace("-", ":");

// Code Connect files indexed by Figma node id (same reading as scripts/contract-check.mjs).
const substitutions = JSON.parse(read("figma.config.json")).codeConnect.documentUrlSubstitutions || {};
const codeConnect = new Map();
for (const file of walk(at("src/figma")).filter((f) => f.endsWith(".figma.ts"))) {
  const text = fs.readFileSync(file, "utf8");
  const header = (key) => text.match(new RegExp(`^// ${key}=(.+)$`, "m"))?.[1].trim();
  const url = header("url");
  const id = nodeIdOf(substitutions[url] ?? url);
  if (id) codeConnect.set(id, { component: header("component"), source: header("source")?.match(/\/blob\/[^/]+\/(.+)$/)?.[1] });
}

const rows = fs
  .readdirSync(at("docs/components"))
  .filter((f) => f.endsWith(".contract.json"))
  .sort()
  .map((f) => {
    const name = f.replace(".contract.json", "");
    const contract = JSON.parse(read("docs/components", f));
    const exported = contract.exportedAt?.slice(0, 10) ?? "";
    const notes = [];

    const cc = codeConnect.get(nodeIdOf(contract.figmaUrl));
    const code = Boolean(cc?.source && exists(cc.source));

    // The story file is named after the folder of the React component and has to mention the component.
    const folder = cc?.source?.match(/primitives\/([^/]+)\//)?.[1];
    const storyFile = folder && `src/stories/primitives/${folder}.stories.tsx`;
    const story = Boolean(storyFile && exists(storyFile) && cc.component && new RegExp(`\\b${cc.component}\\b`).test(read(storyFile)));

    let review = "None";
    let reviewDate = "";
    if (exists("eval/scorecards", `${name}.md`)) {
      const head = read("eval/scorecards", `${name}.md`).match(/Round:\s*(\d+)\s*\|\s*Date:\s*([\d-]+)\s*\|\s*Verdict:\s*(\w+)/);
      if (head) {
        review = `${head[3]} (round ${head[1]}, ${head[2]})`;
        reviewDate = head[2];
        if (exported > reviewDate) notes.push("Contract exported after the last review: review again.");
      }
    }
    const passed = review.startsWith("Pass");

    const images = exists("docs/pages/img", name) ? fs.readdirSync(at("docs/pages/img", name)).filter((i) => i.endsWith(".png")) : [];
    const anatomy = images.some((i) => i.startsWith("anatomy"));
    const illustrations = images.length ? `${images.length}${anatomy ? "" : ", no anatomy"}` : "None";

    const page = exists("docs/pages", `${name}.md`) ? `docs/pages/${name}.md` : exists("docs/supernova", `${name}.md`) ? `docs/supernova/${name}.md` : null;
    if (page && !passed) notes.push("Has a documentation page without a passing review.");
    if (page && !page.startsWith("docs/pages/")) notes.push("Documentation source is in the old folder.");

    const built = code && story;
    const status = !cc ? "Audited" : !built ? "In build" : !passed ? "Built" : images.length && anatomy && page ? "Documented" : "Reviewed";

    return { name: contract.component ?? name, status, audit: `${contract.readinessScore ?? "?"}%`, exported, code, codeConnect: Boolean(cc), story, review, illustrations, page: page ? "Yes" : "No", notes: notes.join(" ") };
  });

const yes = (v) => (v ? "Yes" : "No");
const order = ["Documented", "Reviewed", "Built", "In build", "Audited"];
rows.sort((a, b) => order.indexOf(a.status) - order.indexOf(b.status) || a.name.localeCompare(b.name));

const out = [
  "# Component status",
  "",
  "Generated by `npm run status` from the files of the repository. Do not edit by hand: change the source file and run the command again.",
  "",
  "## How the status is calculated",
  "",
  "| Status | Means |",
  "|---|---|",
  "| Audited | The RubyLint contract is in `docs/components/`. Nothing else yet. |",
  "| In build | A Code Connect file points at the Figma component, but the React component or its story is missing. |",
  "| Built | React component, Code Connect file and story exist. No passing review. |",
  "| Reviewed | The latest scorecard in `eval/scorecards/` says Pass. |",
  "| Documented | Reviewed, and the illustrations (anatomy included) and the documentation source exist. |",
  "",
  "A component goes back a step by itself: a new contract export after the last review asks for a new review (see Notes).",
  "",
  "## Components",
  "",
  "| Component | Status | Audit | Contract exported | React | Code Connect | Story | Review | Illustrations | Documentation | Notes |",
  "|---|---|---|---|---|---|---|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.status} | ${r.audit} | ${r.exported} | ${yes(r.code)} | ${yes(r.codeConnect)} | ${yes(r.story)} | ${r.review} | ${r.illustrations} | ${r.page} | ${r.notes} |`),
  "",
  "## Where each column comes from",
  "",
  "| Column | Source |",
  "|---|---|",
  "| Audit, Contract exported | `readinessScore` and `exportedAt` in `docs/components/<Name>.contract.json` |",
  "| Code Connect | A file in `src/figma/` whose `url=` header resolves to the node of the contract's `figmaUrl` |",
  "| React | The file named in the `source=` header of that Code Connect file |",
  "| Story | `src/stories/primitives/<Component>.stories.tsx` mentions the component named in the `component=` header |",
  "| Review | First line of `eval/scorecards/<Name>.md` (round, date, verdict) |",
  "| Illustrations | PNG files in `docs/pages/img/<Name>/` |",
  "| Documentation | `docs/pages/<Name>.md` |",
  "",
  "Not in this table, because the repository does not hold them: whether Code Connect is published in Figma, and whether the documentation is published in Supernova.",
  "",
].join("\n");

const target = at("docs/components.md");
const summary = order.map((s) => `${rows.filter((r) => r.status === s).length} ${s.toLowerCase()}`).join(", ");
if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.log("error docs/components.md is out of date. Run npm run status and commit the result.");
    process.exit(1);
  }
  console.log(`component status: up to date (${rows.length} components: ${summary})`);
} else {
  fs.writeFileSync(target, out);
  console.log(`component status: ${rows.length} components: ${summary}. Written to docs/components.md`);
}
